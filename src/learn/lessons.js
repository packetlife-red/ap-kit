// 「はじめから」モードのレッスン定義。
//
// ドリル（core/generators）とは目的がまったく違う。
// ドリルは「解ける人が反復する」ための無限生成器。こちらは「まだ解けない人が
// ゼロから読んで分かる」ための読み物で、数値は固定（＝説明文と必ず整合する）。
//
// 1レッスン ＝ read（読む）→ walk（一緒に解く）→ try（自分で解く）の3段。
//   read … 用語と考え方。問題は出さない
//   walk … 例題を穴埋めで追う。間違えても減点しない・正解を先に見てよい
//   try  … 初めて自力。ヒント常時表示、間違えたら答えを出さずに再挑戦させる
//
// try の数値は「暗算できる」ことを最優先に選んである。
// 0.9192 のような数が出た時点で初学者は計算そのもので詰まるため。

